#!/usr/bin/env node
/*
 * Copies the shared/ files into the places that need them. Apps Script and
 * GitHub Pages have no build step, so each place gets a real copy.
 *
 *   npm run sync                          copy shared/ files into place
 *   node scripts/sync-shared.js --check   exit 1 if any copy is out of date
 *
 * Apps Script can't serve plain .js/.css to the browser, so browser-side code
 * for the admin page is wrapped in <script>/<style> as an .html file that
 * Index.html includes.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');

const GENERATED_NOTE = 'GENERATED by `npm run sync` from SRC. Do not edit here.';

const COPIES = [
  { src: 'shared/signin-rules.js', dest: 'web/signin-rules.js' },
  { src: 'shared/signin-rules.js', dest: 'apps-script/endpoint/signin-rules.js' },
  { src: 'shared/sheet-core.js', dest: 'apps-script/admin/sheet-core.js' },
  { src: 'shared/sheet-core.js', dest: 'apps-script/endpoint/sheet-core.js' },
  { src: 'shared/qr-render.js', dest: 'apps-script/admin/QrRender.html', wrap: 'script' },
  { src: 'shared/print-sheet.css', dest: 'apps-script/admin/PrintStyles.html', wrap: 'style' }
];

function expected(entry) {
  const body = fs.readFileSync(path.join(ROOT, entry.src), 'utf8');
  if (!entry.wrap) return body;
  const note = GENERATED_NOTE.replace('SRC', entry.src);
  if (entry.wrap === 'script') return `<script>\n/* ${note} */\n${body}</script>\n`;
  if (entry.wrap === 'style') return `<style>\n/* ${note} */\n${body}</style>\n`;
  throw new Error('Unknown wrap: ' + entry.wrap);
}

function outOfDate() {
  const stale = [];
  for (const entry of COPIES) {
    const p = path.join(ROOT, entry.dest);
    const have = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (have !== expected(entry)) stale.push({ src: entry.src, target: entry.dest });
  }
  return stale;
}

function main() {
  const check = process.argv.includes('--check');
  const stale = outOfDate();
  if (check) {
    if (stale.length) {
      for (const s of stale) console.error(`Out of date: ${s.target} (from ${s.src}). Run: npm run sync`);
      process.exit(1);
    }
    console.log('Shared copies are up to date.');
    return;
  }
  for (const s of stale) {
    const entry = COPIES.find((e) => e.dest === s.target);
    fs.writeFileSync(path.join(ROOT, entry.dest), expected(entry));
    console.log(`Copied ${s.src} -> ${s.target}`);
  }
  if (!stale.length) console.log('Shared copies are already up to date.');
}

if (require.main === module) main();

module.exports = { COPIES, outOfDate, expected };
